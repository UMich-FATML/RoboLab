"""Batch scene/task generation (CPU). See docs/scene_gen_pipeline.md.

    python scripts/scenegen.py build-geometry            # per-asset mesh geometry (cached) + summary JSON
    python scripts/scenegen.py generate --num-tasks 20 --seed 0
    python scripts/scenegen.py validate-cpu
    # ... settle on a GPU node: assets/scenes/_utils/settle_scenes.py --scene assets/scenes/generated --replace
    python scripts/scenegen.py check-settled
    python scripts/scenegen.py generate --num-tasks 20 --seed 0   # tops up settle rejections

Needs pxr (any IsaacSim venv) but no GPU. Set OMNI_KIT_ACCEPT_EULA=Y on the 6.x stack.
"""

import argparse
import json
import logging
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from robolab.constants import ASSET_DIR  # noqa: E402
from robolab.scene_gen import pipeline  # noqa: E402

GEOMETRY_SUMMARY = Path(ASSET_DIR) / "objects" / "scenegen_geometry.json"


def build_geometry() -> int:
    from robolab.scene_gen.catalog import Catalog

    cat = Catalog()
    summary = {
        "note": "Generated by scripts/scenegen.py build-geometry from the asset meshes; heightmaps are cached "
                "locally in assets/objects/.scenegen_cache/. Do not edit.",
        "objects": {name: _round(o.geom.summary()) for name, o in sorted(cat.objects.items())},
        "excluded": {k: v for k, v in sorted(cat.excluded.items()) if not k.endswith("#dup")},
    }
    GEOMETRY_SUMMARY.write_text(json.dumps(summary, indent=1, sort_keys=True) + "\n")
    roles = {"container": sum(o.is_container for o in cat.objects.values()),
             "support": sum(o.is_support for o in cat.objects.values()),
             "graspable": sum(o.graspable for o in cat.objects.values())}
    print(f"{len(cat.objects)} objects ({roles}); excluded {len(summary['excluded'])}; wrote {GEOMETRY_SUMMARY}")
    return 0


def _round(x):
    if isinstance(x, float):
        return round(x, 5)
    if isinstance(x, (list, tuple)):
        return [_round(v) for v in x]
    if isinstance(x, dict):
        return {k: _round(v) for k, v in x.items()}
    return x


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("build-geometry")
    g = sub.add_parser("generate")
    g.add_argument("--num-tasks", type=int, required=True)
    g.add_argument("--seed", type=int, default=0)
    g.add_argument("--max-attempts", type=int, default=None)
    g.add_argument("--scene-out", type=Path, default=pipeline.DEFAULT_SCENE_OUT)
    g.add_argument("--task-out", type=Path, default=pipeline.DEFAULT_TASK_OUT)
    v = sub.add_parser("validate-cpu")
    v.add_argument("--scene-out", type=Path, default=pipeline.DEFAULT_SCENE_OUT)
    c = sub.add_parser("check-settled")
    c.add_argument("--scene-out", type=Path, default=pipeline.DEFAULT_SCENE_OUT)
    c.add_argument("--max-displacement", type=float, default=pipeline.SETTLE_MAX_DISPLACEMENT)
    c.add_argument("--dry-run", action="store_true", help="report only; do not reject scenes")
    args = ap.parse_args()
    logging.basicConfig(level=logging.WARNING)

    if args.cmd == "build-geometry":
        return build_geometry()
    if args.cmd == "generate":
        stats = pipeline.generate(args.num_tasks, args.seed, args.scene_out, args.task_out, args.max_attempts)
        print(json.dumps(stats))
        return 0 if stats["live"] >= args.num_tasks else 1
    if args.cmd == "validate-cpu":
        failures = pipeline.validate_cpu(args.scene_out)
        for f in failures:
            print("FAIL", f)
        return 1 if failures else 0
    if args.cmd == "check-settled":
        report = pipeline.check_settled(args.scene_out, args.max_displacement, apply=not args.dry_run)
        return 1 if report["rejected"] or report["unsettled"] else 0
    return 2


if __name__ == "__main__":
    sys.exit(main())
